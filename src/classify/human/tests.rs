//! Tests for telling typed prompts from harness traffic.

use super::{Reason, classify};
use crate::testing::{TestResult, check_eq};
use crate::transcript::entry::decode_line;

#[test]
fn classify_checks_the_role_markers_and_origin_first() -> TestResult {
    for (name, line, want) in [
        (
            "typed prompt",
            r#"{"type":"user","message":{"role":"user","content":"draft the weekly report"}}"#,
            Reason::Human,
        ),
        (
            "session title",
            r#"{"type":"ai-title","aiTitle":"Weekly report"}"#,
            Reason::NotUser,
        ),
        (
            "injected skill body",
            r#"{"type":"user","isMeta":true,"message":{"role":"user","content":"Base directory for this skill: /skills/tdd"}}"#,
            Reason::Meta,
        ),
        (
            "sub-agent prompt",
            r#"{"type":"user","isSidechain":true,"message":{"role":"user","content":"explore the repo"}}"#,
            Reason::Sidechain,
        ),
        (
            "compaction summary",
            r#"{"type":"user","isCompactSummary":true,"message":{"role":"user","content":"This session is being continued"}}"#,
            Reason::CompactSummary,
        ),
        (
            "human origin",
            r#"{"type":"user","origin":{"kind":"human"},"message":{"role":"user","content":"draft the weekly report"}}"#,
            Reason::Human,
        ),
        (
            "task notification origin",
            r#"{"type":"user","origin":{"kind":"task-notification"},"message":{"role":"user","content":"background task finished"}}"#,
            Reason::NonHumanOrigin,
        ),
        (
            "peer message origin",
            r#"{"type":"user","origin":{"kind":"peer"},"message":{"role":"user","content":"hello from another session"}}"#,
            Reason::NonHumanOrigin,
        ),
    ] {
        let entry = decode_line(line.as_bytes()).ok_or(name)?;
        check_eq(&classify(&entry), &want, name)?;
    }
    Ok(())
}

#[test]
fn classify_then_checks_the_body() -> TestResult {
    for (name, line, want) in [
        (
            "tool result",
            r#"{"type":"user","message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"t-1","content":"ok"}]}}"#,
            Reason::ToolResult,
        ),
        (
            "prompt with a pasted image",
            r#"{"type":"user","message":{"role":"user","content":[{"type":"text","text":"why is this blank?"},{"type":"image","source":{"type":"base64","media_type":"image/png","data":"iVBORw0KGgo="}}]}}"#,
            Reason::Human,
        ),
        (
            "system reminder",
            r#"{"type":"user","message":{"role":"user","content":"<system-reminder>\nfiles changed\n</system-reminder>"}}"#,
            Reason::HarnessTag,
        ),
        (
            "task notification body after leading whitespace",
            r#"{"type":"user","message":{"role":"user","content":"\n  <task-notification><task-id>1</task-id></task-notification>"}}"#,
            Reason::HarnessTag,
        ),
        (
            "local command caveat",
            r#"{"type":"user","message":{"role":"user","content":"<local-command-caveat>Caveat: generated by local commands</local-command-caveat>"}}"#,
            Reason::HarnessTag,
        ),
        (
            "shell escape is recorded as human but is not a prompt",
            r#"{"type":"user","origin":{"kind":"human"},"message":{"role":"user","content":"<bash-input>git push</bash-input>"}}"#,
            Reason::HarnessTag,
        ),
        (
            "shell output",
            r#"{"type":"user","message":{"role":"user","content":"<bash-stdout>ok</bash-stdout><bash-stderr></bash-stderr>"}}"#,
            Reason::HarnessTag,
        ),
        (
            "prompt-submit hook output",
            r#"{"type":"user","message":{"role":"user","content":"<user-prompt-submit-hook>blocked</user-prompt-submit-hook>"}}"#,
            Reason::HarnessTag,
        ),
        (
            "tag in the middle of a typed prompt",
            r#"{"type":"user","message":{"role":"user","content":"why does <system-reminder> appear in my log?"}}"#,
            Reason::Human,
        ),
        (
            "whitespace only",
            r#"{"type":"user","message":{"role":"user","content":"  \n "}}"#,
            Reason::Empty,
        ),
        (
            "interruption marker",
            r#"{"type":"user","message":{"role":"user","content":[{"type":"text","text":"[Request interrupted by user for tool use]"}]}}"#,
            Reason::Interrupted,
        ),
        // Only ASCII whitespace is skipped before a tag, so an ideographic
        // space hides it, while trimming for the other checks still strips
        // the space.
        (
            "tag after an ideographic space is a prompt",
            r#"{"type":"user","message":{"role":"user","content":"\u3000<system-reminder>x"}}"#,
            Reason::Human,
        ),
        (
            "an assistant line",
            r#"{"type":"assistant","message":{"content":[{"type":"text","text":"done"}]}}"#,
            Reason::NotUser,
        ),
    ] {
        let entry = decode_line(line.as_bytes()).ok_or(name)?;
        check_eq(&classify(&entry), &want, name)?;
    }
    Ok(())
}
